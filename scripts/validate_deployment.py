#!/usr/bin/env python3
"""
validate_deployment.py — verify a microservice's helm-values/ deployment files.

Checks (see references/configmap-catalog.md and validation-rules.md):
  * per-env path convention for vault/infra/ff paths, incl. the prod-eu -> infra/prod fold
  * region field matches the env
  * AWS_SM_API_VERSION / PORT constants
  * configMap.data key parity across env files (vs the base dev file)
  * HPA placeholder token in base values.yaml; quoted-string booleans
  * labels.team in the allowed list
  * required fields (serviceName, microservicesName[].name/repo/dockerFileLocation/labels)
  * autoscalingMinReplicas >= 2 for qa/uat/prod tiers when HPA on
  * prod-family imageTag ends in -UTC
  * optional (--workflows): .github/workflows/*.yaml against the shared-library reusable
    workflow input contract
  * optional (--helm): helm lint/template if the devops-infra chart is discoverable

Environment/team/regex knowledge is loaded from data/contract.json (the single source of
truth generated by sync_contract.py). When that file is absent — e.g. this script has been
copied standalone into a service repo — it falls back to the baked-in literals below, so it
always runs.

Usage:
  python3 validate_deployment.py [--dir helm-values] [--helm] [--workflows] [--strict]
                                 [--team ai-solutions] [--contract PATH]
Exit code: 0 = ok (warnings allowed), 1 = errors found.

Dependency: PyYAML (pip install pyyaml).
"""
import argparse
import json
import os
import re
import sys

try:
    import yaml
except ImportError:
    sys.stderr.write("ERROR: PyYAML required. Install with: pip install pyyaml\n")
    sys.exit(2)

# ---------------------------------------------------------------------------
# FALLBACK knowledge base — used only when data/contract.json is not found.
# Keep roughly in sync with the contract; the contract (when present) wins.
# ---------------------------------------------------------------------------
_FALLBACK_ENV_META = {
    "dev":      {"region": "us-west-2",      "tier": "dev",      "infra": "dev",      "ff": "dev"},
    "test":     {"region": "us-west-2",      "tier": "test",     "infra": "test",     "ff": "test"},
    "qa":       {"region": "us-east-1",      "tier": "qa",       "infra": "qa",       "ff": "qa"},
    "perf":     {"region": "us-west-2",      "tier": "perf",     "infra": "perf",     "ff": "perf"},
    "perft":    {"region": "us-west-2",      "tier": "perft",    "infra": "perft",    "ff": "perft"},
    "migt":     {"region": "us-west-2",      "tier": "migt",     "infra": "migt",     "ff": "migt"},
    "non-prod": {"region": "us-west-2",      "tier": "non-prod", "infra": "non-prod", "ff": "non-prod"},
    "uat":      {"region": "us-west-2",      "tier": "uat",      "infra": "uat",      "ff": "uat"},
    "uat-eu":   {"region": "eu-west-1",      "tier": "uat",      "infra": "uat-eu",   "ff": "uat-eu"},
    "uat-ca":   {"region": "ca-central-1",   "tier": "uat",      "infra": "uat-ca",   "ff": "uat-ca"},
    "uat-au":   {"region": "ap-southeast-2", "tier": "uat",      "infra": "uat-au",   "ff": "uat-au"},
    "prod":     {"region": "us-west-2",      "tier": "prod",     "infra": "prod",     "ff": "prod"},
    "prod-eu":  {"region": "eu-west-1",      "tier": "prod",     "infra": "prod",     "ff": "prod"},   # EU folds into prod
    "prod-ca":  {"region": "ca-central-1",   "tier": "prod",     "infra": "prod-ca",  "ff": "prod"},
    "prod-au":  {"region": "ap-southeast-2", "tier": "prod",     "infra": "prod-au",  "ff": "prod"},
}
_FALLBACK_PROD_FAMILY = {"qa", "uat", "prod"}
_FALLBACK_TEAMS = {"platform", "integration", "search", "content", "DE", "NL", "LS",
                   "recognition", "frontend", "other",
                   "ai-solutions", "data-engineering", "de-pi"}
_FALLBACK_UTC_RE = r"^[A-Za-z0-9.-]+-\d{4}-\d{2}-\d{2}-\d{2}\.\d{2}\.\d{2}-UTC$"

REGION_KEYS = ("AWS_SM_REGION", "AWS_REGION", "AWS_DEFAULT_REGION")

# Live config — populated by configure(); defaults to the fallback literals.
ENV_META = dict(_FALLBACK_ENV_META)
PROD_FAMILY = set(_FALLBACK_PROD_FAMILY)
ALLOWED_TEAMS = set(_FALLBACK_TEAMS)
UTC_TAG_RE = re.compile(_FALLBACK_UTC_RE)
AWS_SM_API_VERSION = "2017-10-17"
DEFAULT_PORT = "5000"
CONTRACT = None

errors, warnings = [], []
EXPECTED_TEAM = None  # set via --team to hard-enforce a specific labels.team


# --------------------------------------------------------------------------- contract
def find_contract_path(explicit=None):
    """Locate data/contract.json. Search order: explicit arg, then data/contract.json
    relative to this script (data/contract.json)."""
    if explicit:
        return explicit if os.path.isfile(explicit) else None
    here = os.path.dirname(os.path.abspath(__file__))          # scripts/
    cand = os.path.join(os.path.dirname(here), "data", "contract.json")
    return cand if os.path.isfile(cand) else None


def load_contract(explicit=None):
    path = find_contract_path(explicit)
    if not path:
        return None
    try:
        with open(path) as f:
            return json.load(f)
    except Exception as e:
        sys.stderr.write(f"WARN: could not read contract {path}: {e}; using fallback\n")
        return None


def _env_meta_from_contract(contract):
    """Map contract environments -> the validator's internal {region,tier,infra,ff} shape."""
    out = {}
    for env, m in (contract.get("environments") or {}).items():
        out[env] = {
            "region": m.get("region"),
            "tier": m.get("tier"),
            "infra": m.get("infraSeg"),
            "ff": m.get("ffSeg"),
        }
    return out


def configure(contract):
    """Apply a loaded contract to the module-level config. No-op (keeps fallback) if None."""
    global ENV_META, PROD_FAMILY, ALLOWED_TEAMS, UTC_TAG_RE, CONTRACT
    global AWS_SM_API_VERSION, DEFAULT_PORT
    CONTRACT = contract
    if not contract:
        return
    em = _env_meta_from_contract(contract)
    if em:
        ENV_META = em
    rules = contract.get("derivedRules") or {}
    if rules.get("minReplicaTiers"):
        PROD_FAMILY = set(rules["minReplicaTiers"])
    if rules.get("awsSmApiVersion"):
        AWS_SM_API_VERSION = rules["awsSmApiVersion"]
    if rules.get("defaultPort"):
        DEFAULT_PORT = str(rules["defaultPort"])
    teams = (contract.get("teams") or {}).get("labelTeams")
    if teams:
        ALLOWED_TEAMS = set(teams)
    rx = (contract.get("imageTag") or {}).get("strictUtcRegex")
    if rx:
        try:
            UTC_TAG_RE = re.compile(rx)
        except re.error:
            pass


def err(msg):
    errors.append(msg)


def warn(msg):
    warnings.append(msg)


def env_from_filename(fn):
    m = re.match(r"^(.*)-values\.yaml$", os.path.basename(fn))
    return m.group(1) if m else None


def load(path):
    with open(path) as f:
        return yaml.safe_load(f) or {}


# --------------------------------------------------------------------------- checks
def check_paths(env, data, fname):
    """Scan configMap.data values for path-token drift."""
    meta = ENV_META.get(env)
    if not meta:
        warn(f"{fname}: unknown environment '{env}' — not in contract/ENV_META, skipping path checks")
        return
    cm = (data.get("configMap") or {}).get("data") or {}
    if not cm:
        warn(f"{fname}: no configMap.data block")
        return

    # region field
    for k in REGION_KEYS:
        if k in cm and str(cm[k]).strip() != meta["region"]:
            err(f"{fname}: {k}={cm[k]!r} but env '{env}' region should be '{meta['region']}'")

    # constants
    if "AWS_SM_API_VERSION" in cm and str(cm["AWS_SM_API_VERSION"]).strip() != AWS_SM_API_VERSION:
        warn(f"{fname}: AWS_SM_API_VERSION={cm['AWS_SM_API_VERSION']!r} (expected '{AWS_SM_API_VERSION}')")
    if "PORT" in cm and str(cm["PORT"]).strip() not in (DEFAULT_PORT,):
        warn(f"{fname}: PORT={cm['PORT']!r} (convention is '{DEFAULT_PORT}')")

    for key, val in cm.items():
        if not isinstance(val, str):
            continue
        v = val.strip()
        # vault/<tier>/<ns>  -> tier only, never region suffix
        m = re.match(r"^vault/([^/]+)/", v)
        if m:
            seg = m.group(1)
            if seg != meta["tier"]:
                err(f"{fname}: {key}={v!r} -> vault segment '{seg}' should be '{meta['tier']}' "
                    f"(vault paths use the tier, never a region suffix)")
        # Any vault path of the form <prefix>/<envtoken>/static/... embeds an env token in the
        # segment right before 'static'. Two cases:
        #   * infra/... -> STRICT: token must equal infraSeg (prod-eu folds to 'prod'; ca/au suffix).
        #   * service-prefixed (e.g. custom-themes-app/...) -> TOLERANT: accept either the folded
        #     infraSeg OR the full env name; warn otherwise (catches copy-paste drift).
        sm = re.search(r"(?:^|/)([^/]+)/static/", v)
        if sm:
            seg = sm.group(1)
            if v.startswith("infra/"):
                if seg != meta["infra"]:
                    hint = ""
                    if env == "prod-eu":
                        hint = "  (prod-eu FOLDS into 'infra/prod' — do NOT use 'infra/prod-eu')"
                    elif env in ("prod-ca", "prod-au", "uat-ca", "uat-au", "uat-eu"):
                        hint = f"  ('{env}' keeps its region suffix)"
                    err(f"{fname}: {key}={v!r} -> infra segment '{seg}' should be '{meta['infra']}'{hint}")
            else:
                acceptable = {meta["infra"], env}  # folded OR full env
                if seg not in acceptable:
                    exp = " or ".join(f"'{a}'" for a in sorted(acceptable))
                    warn(f"{fname}: {key}={v!r} -> env token '{seg}' before /static/ should be "
                         f"{exp} — verify this vault path wasn't copy-pasted from another env")
        # <ffSeg>/harness  (feature flags) -- WARN: region-suffix convention varies by service.
        m = re.match(r"^([^/]+)/harness$", v)
        if m:
            seg = m.group(1)
            if seg != meta["ff"]:
                hint = "  (prod tier should drop region: 'prod/harness')" if meta["tier"] == "prod" else \
                       "  (uat usually keeps region, e.g. 'uat-eu/harness' — verify vs your vault layout)"
                warn(f"{fname}: {key}={v!r} -> harness/ff segment '{seg}' != expected '{meta['ff']}'{hint}")


def check_base(data, fname):
    if not data.get("serviceName"):
        err(f"{fname}: missing required top-level 'serviceName'")
    ms = data.get("microservicesName") or {}
    if not ms:
        err(f"{fname}: no 'microservicesName' entries")
    for key, svc in ms.items():
        svc = svc or {}
        for req in ("name", "repo", "dockerFileLocation"):
            if not svc.get(req):
                err(f"{fname}: microservicesName.{key} missing '{req}'")
        if svc.get("name") and svc.get("labels", {}).get("name") and svc["name"] != svc["labels"]["name"]:
            err(f"{fname}: microservicesName.{key}: name '{svc['name']}' != labels.name "
                f"'{svc['labels']['name']}' (must match)")
        team = (svc.get("labels") or {}).get("team")
        if team and EXPECTED_TEAM and team != EXPECTED_TEAM:
            err(f"{fname}: microservicesName.{key}.labels.team='{team}' must be "
                f"'{EXPECTED_TEAM}' (enforced via --team)")
        elif team and team not in ALLOWED_TEAMS:
            warn(f"{fname}: microservicesName.{key}.labels.team='{team}' not in allowed set "
                 f"{sorted(ALLOWED_TEAMS)}")
        # HPA placeholder token lets the pipeline force HPA off in dev/test/migt.
        hpa = svc.get("isHpaEnabled")
        if hpa not in ("HPA-REPLACE-WITH-TRUE-FALSE", None):
            warn(f"{fname}: microservicesName.{key}.isHpaEnabled={hpa!r} in base values.yaml; "
                 f"prefer the literal token 'HPA-REPLACE-WITH-TRUE-FALSE' so the pipeline can "
                 f"force HPA off in dev/test/migt")


def check_env_overrides(env, data, fname):
    meta = ENV_META.get(env, {})
    tier = meta.get("tier")
    for key, svc in (data.get("microservicesName") or {}).items():
        svc = svc or {}
        if tier in PROD_FAMILY and svc.get("isHpaEnabled") is True:
            mn = svc.get("autoscalingMinReplicas")
            if isinstance(mn, int) and mn < 2:
                warn(f"{fname}: microservicesName.{key}.autoscalingMinReplicas={mn} < 2 "
                     f"(qa/uat/prod recommended >= 2 for HA; some services intentionally run 1)")
        tag = svc.get("imageTag")
        if tier == "prod" and tag and not UTC_TAG_RE.match(str(tag)):
            warn(f"{fname}: microservicesName.{key}.imageTag={tag!r} does not look like a "
                 f"released '-UTC' tag")


def check_key_parity(files):
    """configMap.data key set must match the base (dev) file across all envs."""
    base_env = "dev" if "dev" in files else next(iter(files), None)
    if not base_env:
        return
    base_keys = set(((files[base_env].get("configMap") or {}).get("data") or {}).keys())
    if not base_keys:
        return
    for env, data in files.items():
        keys = set(((data.get("configMap") or {}).get("data") or {}).keys())
        missing = base_keys - keys
        extra = keys - base_keys
        if missing:
            err(f"{env}-values.yaml: configMap.data missing keys present in {base_env}: "
                f"{sorted(missing)}")
        if extra:
            warn(f"{env}-values.yaml: configMap.data has extra keys not in {base_env}: "
                 f"{sorted(extra)}")


def _load_workflow(path):
    with open(path) as f:
        doc = yaml.safe_load(f)
    if not isinstance(doc, dict):
        return None
    # YAML parses the bare key `on` as boolean True.
    on = doc.get("on")
    if on is None:
        on = doc.get(True)
    return doc, (on or {})


_USES_RE = re.compile(
    r"[A-Za-z0-9_.-]+/github-shared-library/\.github/workflows/([A-Za-z0-9_.-]+?)\.ya?ml@([A-Za-z0-9_./-]+)")


def check_workflow_inputs(repo_root):
    """Validate .github/workflows/*.yaml calls against the shared-library reusable-workflow
    contract in the loaded contract. No-op if no contract or no workflows dir."""
    if not CONTRACT:
        return
    rw = CONTRACT.get("reusableWorkflows") or {}
    wf_dir = os.path.join(repo_root, ".github", "workflows")
    if not os.path.isdir(wf_dir):
        return
    # Deployable envs = the shared library's branch-gating allow-list (what
    # validate-deployment-input actually accepts). Fall back to the env map if absent.
    gating = CONTRACT.get("branchGating") or {}
    deployable_envs = set(gating.get("developBranchEnvs") or []) \
        | set(gating.get("perftBranchEnvs") or []) \
        | set(gating.get("releaseBranchEnvs") or [])
    if not deployable_envs:
        deployable_envs = set((CONTRACT.get("environments") or {}).keys()) | set(
            (CONTRACT.get("envAliases") or {}).keys())
    has_buildx_multiarch = "multiarch" in (rw.get("service-deploy-buildx", {}).get("refs") or [])

    for fn in sorted(os.listdir(wf_dir)):
        if not (fn.endswith(".yaml") or fn.endswith(".yml")):
            continue
        path = os.path.join(wf_dir, fn)
        try:
            loaded = _load_workflow(path)
        except Exception as e:
            warn(f".github/workflows/{fn}: YAML parse error: {e}")
            continue
        if not loaded:
            continue
        doc, _on = loaded
        for job_name, job in (doc.get("jobs") or {}).items():
            job = job or {}
            uses = job.get("uses")
            if not uses:
                continue
            m = _USES_RE.search(uses)
            if not m:
                continue  # not a shared-library call (e.g. external lib, local job)
            wf_name, ref = m.group(1), m.group(2)
            spec = rw.get(wf_name)
            if not spec:
                # Known shared workflow we just don't deep-track -> stay quiet. Only warn on
                # a name absent from the whole shared library (likely renamed/new upstream).
                if wf_name not in (CONTRACT.get("knownWorkflows") or []):
                    warn(f".github/workflows/{fn} [{job_name}]: calls unknown shared workflow "
                         f"'{wf_name}' — not in shared library (renamed/new? run sync_contract.py)")
                continue
            # ref check
            if spec.get("refs") and ref not in spec["refs"]:
                warn(f".github/workflows/{fn} [{job_name}]: {wf_name}@{ref} — ref '{ref}' not in "
                     f"known refs {spec['refs']} (verify the branch still exists)")
            # legacy single-arch advisory
            if wf_name == "service-deploy" and has_buildx_multiarch:
                warn(f".github/workflows/{fn} [{job_name}]: uses single-arch 'service-deploy'; "
                     f"'service-deploy-buildx@multiarch' is the multi-arch path — confirm intended")
            given = job.get("with") or {}
            declared = spec.get("inputs") or {}
            # required inputs present
            for inp, ispec in declared.items():
                if ispec.get("required") and inp not in given:
                    err(f".github/workflows/{fn} [{job_name}]: {wf_name} missing required input '{inp}'")
            # unknown inputs
            for inp in given:
                if inp not in declared:
                    warn(f".github/workflows/{fn} [{job_name}]: {wf_name} passes unknown input "
                         f"'{inp}' (not in contract; may be newer upstream)")
            # boolean typing for DEPLOY_TO_* toggles
            for inp, val in given.items():
                if inp.startswith("DEPLOY_TO_") and declared.get(inp, {}).get("type") == "boolean":
                    if isinstance(val, str) and val not in ("true", "false") and "${{" not in val:
                        warn(f".github/workflows/{fn} [{job_name}]: {inp}={val!r} should be boolean")
            # static ENVIRONMENT value against the shared-library branch-gating allow-list
            env_val = given.get("ENVIRONMENT")
            if isinstance(env_val, str) and env_val and "${{" not in env_val:
                if deployable_envs and env_val not in deployable_envs:
                    warn(f".github/workflows/{fn} [{job_name}]: ENVIRONMENT='{env_val}' is not "
                         f"a deployable env per shared-library branch gating "
                         f"(allowed: {sorted(deployable_envs)})")
            # secrets: either `secrets: inherit` or required secrets passed
            secrets = job.get("secrets")
            if spec.get("secrets") and secrets != "inherit":
                passed = set((secrets or {}).keys()) if isinstance(secrets, dict) else set()
                for s in spec["secrets"]:
                    if s not in passed:
                        warn(f".github/workflows/{fn} [{job_name}]: {wf_name} may need secret "
                             f"'{s}' (or use `secrets: inherit`)")


def maybe_helm_lint(values_dir):
    """Run helm lint/template if the devops-infra chart can be found nearby."""
    import glob
    import subprocess
    candidates = glob.glob(os.path.join(values_dir, "..", "..", "**",
                                         "devops-infra", "helm", "microservice-deploy"),
                           recursive=True)
    chart = next((c for c in candidates if os.path.isfile(os.path.join(c, "Chart.yaml"))), None)
    if not chart:
        warn("helm: devops-infra/helm/microservice-deploy chart not found nearby; "
             "skipped helm lint/template (checkout the chart and re-run with --helm)")
        return
    base = os.path.join(values_dir, "values.yaml")
    for env in ENV_META:
        envf = os.path.join(values_dir, f"{env}-values.yaml")
        if not os.path.isfile(envf):
            continue
        cmd = ["helm", "template", "svc", chart,
               "-f", os.path.join(chart, "default-values.yaml"),
               "-f", os.path.join(chart, f"{env}-default-values.yaml"),
               "-f", base, "-f", envf, "--set", "image.tag=validate"]
        try:
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                err(f"helm template failed for {env}: {r.stderr.strip().splitlines()[-1] if r.stderr else '?'}")
        except FileNotFoundError:
            warn("helm: binary not found on PATH; skipped helm template")
            return


# --------------------------------------------------------------------------- run
def run(values_dir, team=None, helm=False, workflows=False, repo_root=None):
    """Run all checks against values_dir. Returns (errors, warnings) lists.
    Re-entrant: resets the module-level result lists on each call (used by the tests)."""
    global errors, warnings, EXPECTED_TEAM
    errors, warnings = [], []
    EXPECTED_TEAM = team

    if not os.path.isdir(values_dir):
        err(f"{values_dir} not found")
        return errors, warnings

    files = {}
    for fn in sorted(os.listdir(values_dir)):
        if not fn.endswith("-values.yaml") and fn != "values.yaml":
            continue
        path = os.path.join(values_dir, fn)
        try:
            data = load(path)
        except Exception as e:
            err(f"{fn}: YAML parse error: {e}")
            continue
        if fn == "values.yaml":
            check_base(data, fn)
            continue
        env = env_from_filename(fn)
        files[env] = data
        check_paths(env, data, fn)
        check_env_overrides(env, data, fn)

    check_key_parity(files)

    if workflows:
        root = repo_root or os.path.dirname(os.path.abspath(values_dir.rstrip("/")))
        check_workflow_inputs(root)
    if helm:
        maybe_helm_lint(values_dir)

    return errors, warnings


def run_workflow_check(repo_root):
    """Run only the workflow-input checks against a repo root. Returns (errors, warnings).
    Re-entrant like run(); used for CI-only build repos that have no helm-values/."""
    global errors, warnings
    errors, warnings = [], []
    check_workflow_inputs(repo_root)
    return errors, warnings


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="helm-values", help="path to helm-values dir")
    ap.add_argument("--helm", action="store_true", help="also run helm lint/template")
    ap.add_argument("--workflows", action="store_true",
                    help="also validate .github/workflows against the shared-library contract")
    ap.add_argument("--strict", action="store_true", help="treat warnings as errors")
    ap.add_argument("--team", help="hard-enforce this labels.team value (e.g. ai-solutions)")
    ap.add_argument("--contract", help="path to contract.json (default: auto-discover)")
    ap.add_argument("--print-contract-provenance", action="store_true",
                    help="print contract provenance (SHAs/dates) and exit")
    args = ap.parse_args()

    contract = load_contract(args.contract)
    configure(contract)

    if args.print_contract_provenance:
        if not contract:
            print("no contract.json found (using fallback literals)")
            sys.exit(0)
        print(json.dumps(contract.get("provenance", {}), indent=2))
        sys.exit(0)

    if not os.path.isdir(args.dir):
        sys.stderr.write(f"ERROR: {args.dir} not found\n")
        sys.exit(2)

    # auto-enable workflow validation when a repo .github/workflows exists and a contract is loaded
    repo_root = os.path.dirname(os.path.abspath(args.dir.rstrip("/")))
    do_workflows = args.workflows or (
        contract is not None and os.path.isdir(os.path.join(repo_root, ".github", "workflows")))

    errs, warns = run(args.dir, team=args.team, helm=args.helm,
                      workflows=do_workflows, repo_root=repo_root)

    n_files = len([f for f in os.listdir(args.dir)
                   if f.endswith("-values.yaml") and f != "values.yaml"])
    src = "contract.json" if contract else "fallback literals"
    print(f"\nValidated {n_files} env file(s) in {args.dir}/  (config: {src})")
    for w in warns:
        print(f"  \033[33mWARN\033[0m  {w}")
    for e in errs:
        print(f"  \033[31mERROR\033[0m {e}")
    n_err = len(errs) + (len(warns) if args.strict else 0)
    if n_err:
        print(f"\n\033[31m✗ {len(errs)} error(s), {len(warns)} warning(s)\033[0m")
        sys.exit(1)
    print(f"\n\033[32m✓ OK\033[0m ({len(warns)} warning(s))")


